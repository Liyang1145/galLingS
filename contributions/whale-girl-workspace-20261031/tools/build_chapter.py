"""Bounded v5.0 first-chapter compiler, restored to 0.1.1 behavior."""
from pathlib import Path
import json, re, hashlib
ROOT = Path(__file__).resolve().parents[1]
source = ROOT/'海风与布丁_第一季_全卷_v5.0.md'
lines = source.read_text(encoding='utf-8-sig').splitlines()
out = ['# Generated by tools/build_chapter.py. Edit the compiler or manuscript, not this file.', 'label start:', '    $ affection = 0', '    $ choices_taken = []', '    $ looking_away = False', '    show screen chapter_hud']
mapping = []
def quote(s):
    return json.dumps(s.replace('[','[[').replace('{','{{'),ensure_ascii=False)
def emit(s,indent=4):
    out.append(' '*indent+s)
def segment(start,end,indent=4):
    for n in range(start,end+1):
        s=lines[n-1].strip()
        mapping.append({'source_line':n,'generated_line':len(out)+1})
        if not s or s.startswith(('━','——','（→','【CG预留】','【事件】')):
            continue
        emit('# source line %d'%n,indent)
        if s.startswith('【场景】'):
            mood='golden' if '黄昏前' in s else 'dusk' if '黄昏' in s else 'afternoon' if '午后' in s else 'day'
            emit('scene bg %s with dissolve'%mood,indent)
            emit('$ scene_caption = '+quote(s[4:]),indent)
        elif s.startswith('【BGM】'):
            emit('$ music_cue = '+quote(s[5:]),indent)
            emit('$ apply_music_cue(music_cue)',indent)
        elif s.startswith('【立绘】'):
            emit('$ portrait_cue = '+quote(s[4:]),indent)
            if n==97: emit('$ persistent.cg001 = True',indent)
        elif s.startswith('◆'):
            m=re.search(r'好感度([+-]\d+)',s)
            if not m: raise ValueError((n,s))
            emit('$ affection += '+m[1],indent)
        elif s.startswith('※'):
            emit('tail '+quote(s[1:]),indent)
        elif s.startswith('旁白：'):
            if n==379:
                emit('scene bg camp with dissolve',indent)
                emit('$ scene_caption = "帐篷外 · 黄昏"',indent)
            emit(quote(s[3:]),indent)
        elif s.startswith('鲸鱼小姐「'):
            emit('whale '+quote(s[len('鲸鱼小姐「'):-1]),indent)
        elif s.startswith('我：「'):
            emit('hero '+quote(s[len('我：「'):-1]),indent)
        elif n==99:
            continue
        elif s.startswith('（尾鳍'):
            emit('tail '+quote(s.strip('（）')),indent)
        else:
            raise ValueError('Unclassified source line %d: %s'%(n,s))
menus=[
 (106,[107,108,109],[(112,114),(117,119),(122,128)],(130,146)),
 (147,[148,149,150],[(153,157),(160,167),(170,172)],(174,237)),
 (238,[239,240,241],[(244,253),(256,264),(267,275)],(277,298)),
 (299,[300,301,302],[(305,319),(322,326),(329,333)],(335,396)),
]
segment(56,105)
for index,(_,options,branches,following) in enumerate(menus,1):
    emit('menu:')
    for k,(option,span) in enumerate(zip(options,branches)):
        text=lines[option-1].strip()[2:].strip().strip('「」')
        emit(quote(text)+':',8)
        emit('$ choices_taken.append(%s)'%quote('%d%s'%(index,'ABC'[k])),12)
        if index==3: emit('$ looking_away = %s'%(k==1),12)
        segment(*span,indent=12)
    segment(*following)
emit('$ persistent.chapter_one_complete = True')
emit('$ renpy.save("auto-chapter-one", extra_info="SP-001 酸梅汤·加桂花")')
emit('hide screen chapter_hud')
emit('call screen chapter_end')
emit('return')
(ROOT/'Seabreeze/game/chapter01.rpy').write_text('\n'.join(out)+'\n',encoding='utf-8')
(ROOT/'tools/source_map.json').write_text(json.dumps({'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'mapping':mapping},ensure_ascii=False,indent=2),encoding='utf-8')
print('Compiled chapter one:',len(out),'lines')
